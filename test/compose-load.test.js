test('load: fetch loops per route, percentiles, errors, 429s and other statuses counted apart', async () => {
  const server = createServer((req, res) => {
    if (req.url === '/ok') return setTimeout(() => res.writeHead(200).end('ok'), 2);
    if (req.url === '/limited') return res.writeHead(429).end();
    if (req.url === '/boom') return res.writeHead(503).end();
    res.writeHead(404).end();
  });
  await new Promise((r) => server.listen(0, '127.0.0.1', () => r(undefined)));
  const url = `http://127.0.0.1:${/** @type {import('node:net').AddressInfo} */ (server.address()).port}`;
  try {
    const lt = new LoadTest({ baseUrl: `${url}/`, durationMs: 300, concurrency: 3, routes: LoadTest.parseRoutes('GET /ok, GET /limited, GET /boom, GET /missing') });
    const report = await lt.run();
    const by = Object.fromEntries(report.results.map((x) => [x.route, x]));
    assert.ok(by['GET /ok'].requests > 10);
    assert.deepEqual([by['GET /ok'].errors, by['GET /ok'].limited, Object.keys(by['GET /ok'].statuses)], [0, 0, ['200']]);
    assert.ok(Number(by['GET /ok'].p50) >= 1 && Number(by['GET /ok'].p95) >= Number(by['GET /ok'].p50) && Number(by['GET /ok'].max) >= Number(by['GET /ok'].p99));
    assert.equal(by['GET /limited'].limited, by['GET /limited'].requests);
    assert.equal(by['GET /boom'].errors, by['GET /boom'].requests);
    assert.equal(by['GET /missing'].unexpected, by['GET /missing'].requests);
    const table = LoadTest.table(report);
    assert.match(table, /route\s+requests\s+rps\s+p50 ms\s+p95 ms/);
    assert.equal(table.split('\n').length, 6);
    const dead = await new LoadTest({ baseUrl: 'http://127.0.0.1:9', durationMs: 100, concurrency: 1, routes: LoadTest.parseRoutes('GET /x') }).run();
    assert.ok(dead.results[0].errors > 0 && dead.results[0].statuses.network > 0);
  } finally {
    server.close();
  }
  assert.deepEqual([LoadTest.percentile([], 50), LoadTest.percentile([1, 2, 3, 4], 50), LoadTest.percentile([1, 2, 3, 4], 95)], [null, 2, 4]);
  assert.throws(() => LoadTest.parseRoutes('/no-method'), /GET \/path/);
});

test('compose: IP databases in atc-geo/mmdb are mounted and wired only when present', () => {
  const root = mkdtempSync(join(tmpdir(), 'atc-geo-root-'));
  try {
    const c = new Compose({ root, stackDir: root, portOffset: 0 });
    assert.deepEqual(c.geoDatabases(), []);
    mkdirSync(join(root, 'atc-geo', 'mmdb'), { recursive: true });
    writeFileSync(join(root, 'atc-geo', 'mmdb', 'asn.mmdb'), '');
    assert.deepEqual(c.geoDatabases(), [], 'an ASN file alone does not count');
    writeFileSync(join(root, 'atc-geo', 'mmdb', 'city.mmdb'), '');
    assert.deepEqual(c.geoDatabases(), ['city.mmdb', 'asn.mmdb']);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test('load: the writes profile prepares its policy, queue and link and builds direct routes', async () => {
  const root = mkdtempSync(join(tmpdir(), 'atc-load-root-'));
  try {
    const put = (/** @type {string} */ id, /** @type {string} */ text) => { mkdirSync(join(root, id), { recursive: true }); writeFileSync(join(root, id, '.env'), text); };
    put('atc-console', 'RATELIMIT_API_KEY=rk\nQUEUE_API_KEY=qk\nSHORTLINK_API_KEY=sk\n');
    put('atc-ratelimit', 'PORT=3011\n');
    put('atc-queue', 'PORT=3016\n');
    put('atc-shortlink', 'PORT=3006\nPUBLIC_BASE_URL=http://127.0.0.1:3006/\n');
    /** @type {string[]} */ const calls = [];
    const fake = /** @type {typeof fetch} */ (async (url, init) => {
      calls.push(`${init?.method} ${url} ${new Headers(init?.headers).get('authorization')}`);
      return new Response(JSON.stringify({ link: { code: 'abc' } }), { status: 201 });
    });
    const routes = await LoadTest.writeProfile(root, fake);
    assert.deepEqual(calls, ['POST http://127.0.0.1:3011/v1/policies Bearer rk', 'PUT http://127.0.0.1:3016/v1/queues/loadtest Bearer qk', 'POST http://127.0.0.1:3006/v1/links Bearer sk']);
    assert.deepEqual(routes.map((r) => r.url), ['http://127.0.0.1:3011/v1/check', 'http://127.0.0.1:3016/v1/queues/loadtest/messages', 'http://127.0.0.1:3016/v1/queues/loadtest/pull', 'http://127.0.0.1:3006/abc']);
    rmSync(join(root, 'atc-console', '.env'));
    put('atc-console', '');
    await assert.rejects(() => LoadTest.writeProfile(root, fake), /RATELIMIT_API_KEY is missing/);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test('deps: audit and outdated are read per service, high findings fail, the SBOM is written per service', async () => {
  const { Deps } = await import('../src/deps.js');
  const calls = [];
  const exec = async (/** @type {string} */ cwd, /** @type {string[]} */ argv) => {
    calls.push(`${cwd.split('/').pop()} ${argv[1]}`);
    if (argv[1] === 'audit') return { code: cwd.endsWith('atc-queue') ? 1 : 0, out: `npm warn something\n${JSON.stringify({ metadata: { vulnerabilities: { low: 1, high: cwd.endsWith('atc-queue') ? 2 : 0 } } })}` };
    if (argv[1] === 'outdated') return { code: 1, out: JSON.stringify({ fastify: { current: '4.1.0', latest: '5.0.0' }, pino: { current: '9.1.0', latest: '9.2.0' } }) };
    return { code: 0, out: JSON.stringify({ bomFormat: 'CycloneDX', components: [] }) };
  };
  const deps = new Deps({ root: '/ws', exec });
  const report = await deps.check();
  assert.equal(report.results.length, SERVICES.length);
  assert.deepEqual([report.results[0].outdated, report.results[0].majorBehind], [2, 1]);
  assert.equal(report.failed, true);
  assert.equal(report.results.find((r) => r.id === 'atc-queue')?.vulnerabilities.high, 2);
  assert.match(Deps.table(report), /service\s+critical\s+high/);
  const out = mkdtempSync(join(tmpdir(), 'atc-sbom-'));
  try {
    const r = await deps.sbom(out);
    assert.equal(r.written.length, SERVICES.length);
    assert.equal(JSON.parse(readFileSync(r.written[0], 'utf8')).bomFormat, 'CycloneDX');
  } finally {
    rmSync(out, { recursive: true, force: true });
  }
});
