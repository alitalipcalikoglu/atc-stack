import { chmodSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { SERVICES } from './manifest.js';

/**
 * Configuration for the stack's MCP server (mcp/). Setup issues a dedicated `atc-mcp` key on every
 * service that has MCP tools, with the smallest role that covers those tools, and writes two
 * untracked, owner-only files at the stack root: `mcp.env` (STACK_MCP_* for every service) and
 * `.mcp.json` (the standard `mcpServers` entry). With read-only mode every key is a `read` key and
 * services without roles (notify, media) get no key at all.
 */
export class McpConfig {
  static HOLDER = 'atc-mcp';
  static ENV_FILE = 'mcp.env';
  static JSON_FILE = '.mcp.json';
  static SERVER_NAME = 'atc-stack';

  /**
   * Role per service: `full` covers every exposed tool (reads and safe writes), `read` only the
   * reads; `undefined` = the service has no roles (its keys are id:secret), `null` = no key.
   * ratelimit's peek check needs `check` or `readwrite`, so a read-only key cannot call it.
   * @type {Readonly<Record<string, { full: string|undefined, read: string|null|undefined }>>}
   */
  static ROLES = Object.freeze({
    'atc-audit': { full: 'read', read: 'read' },
    'atc-auth': { full: 'read', read: 'read' },
    'atc-backup': { full: 'admin', read: 'read' }, // backups.verify needs admin
    'atc-content': { full: 'readwrite', read: 'read' },
    'atc-export': { full: 'readwrite', read: 'read' },
    'atc-flags': { full: 'readwrite', read: 'read' },
    'atc-geo': { full: 'readwrite', read: 'read' },
    'atc-media': { full: undefined, read: null },
    'atc-notify': { full: undefined, read: null },
    'atc-payments': { full: 'write', read: 'read' },
    'atc-queue': { full: 'admin', read: 'read' }, // queues.upsert needs admin
    'atc-ratelimit': { full: 'readwrite', read: 'read' },
    'atc-render': { full: 'readwrite', read: 'read' },
    'atc-scheduler': { full: 'readwrite', read: 'read' },
    'atc-search': { full: 'readwrite', read: 'read' },
    'atc-shortlink': { full: 'readwrite', read: 'read' },
    'atc-status': { full: 'admin', read: 'read' }, // monitors.upsert needs admin
    'atc-webhook-out': { full: 'readwrite', read: 'read' }, // subscriptions write + events publish
  });

  /** @param {{ stackDir: string }} o */
  constructor({ stackDir }) {
    this.stackDir = stackDir;
  }

  get envPath() { return join(this.stackDir, McpConfig.ENV_FILE); }
  get jsonPath() { return join(this.stackDir, McpConfig.JSON_FILE); }

  /** The mode chosen last time (kept by setup), from the existing mcp.env. */
  savedReadOnly() {
    return existsSync(this.envPath) && /^STACK_MCP_READ_ONLY=true$/m.test(readFileSync(this.envPath, 'utf8'));
  }

  /** @param {string} id */
  static prefix(id) {
    return `STACK_MCP_${id.replace(/^atc-/, '').toUpperCase().replace(/-/g, '_')}`;
  }

  /**
   * Issue (or re-role) the atc-mcp keys and return the STACK_MCP_* variables.
   * @param {import('./setup-context.js').SetupContext} ctx @param {{ readOnly: boolean }} o
   * @returns {Record<string, string>}
   */
  issue(ctx, { readOnly }) {
    /** @type {Record<string, string>} */
    const env = { STACK_MCP_READ_ONLY: String(readOnly) };
    for (const s of SERVICES) {
      env[`${McpConfig.prefix(s.id)}_BASE_URL`] = ctx.url(s.id);
      const roles = McpConfig.ROLES[s.id];
      if (!roles || !s.keysVar) continue;
      const role = readOnly ? roles.read : roles.full;
      if (role === null) continue;
      env[`${McpConfig.prefix(s.id)}_API_KEY`] = ctx.issue(s.id, McpConfig.HOLDER, role);
    }
    return env;
  }

  /** @param {Record<string, string>} env */
  envText(env) {
    return ['# Generated by atc-stack (npm run setup / npm run mcp:config). Holds API keys: keep it private, never commit it.', ...Object.entries(env).map(([k, v]) => `${k}=${v}`), ''].join('\n');
  }

  /** The standard `mcpServers` document. @param {Record<string, string>} env */
  json(env) {
    return {
      mcpServers: {
        [McpConfig.SERVER_NAME]: {
          command: 'node',
          args: ['--experimental-strip-types', '--disable-warning=ExperimentalWarning', join(this.stackDir, 'mcp', 'bin', 'stack-mcp.js')],
          env,
        },
      },
    };
  }

  /** Write both files, owner-only. @param {Record<string, string>} env */
  write(env) {
    for (const [path, text] of [[this.envPath, this.envText(env)], [this.jsonPath, `${JSON.stringify(this.json(env), null, 2)}\n`]]) {
      writeFileSync(path, text, { mode: 0o600 });
      chmodSync(path, 0o600);
    }
    return { envPath: this.envPath, jsonPath: this.jsonPath };
  }
}
