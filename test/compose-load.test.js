import assert from 'node:assert/strict';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { createServer } from 'node:http';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { test } from 'node:test';
import { fileURLToPath } from 'node:url';
import { Compose } from '../src/compose.js';
import { LoadTest } from '../src/load-test.js';
import { SERVICES } from '../src/manifest.js';

const workspace = resolve(fileURLToPath(new URL('../..', import.meta.url)));
const ready = SERVICES.every((s) => existsSync(join(workspace, s.id, 'Dockerfile'))) && existsSync(join(workspace, 'atc-auth', 'keys', 'jwt-private.pem'));

test('compose: every service from its Dockerfile, container URLs, image paths, private env files, few published ports', { skip: !ready && 'needs the full workspace after "npm run setup"' }, () => {
  const out = mkdtempSync(join(tmpdir(), 'atc-compose-'));
  try {
    const r = new Compose({ root: workspace, stackDir: out, portOffset: 10_000 }).generate();
    assert.deepEqual([r.services, r.published], [SERVICES.length, ['atc-gateway 13000', 'atc-console 13004', 'atc-media 13003']]);
    const yml = readFileSync(r.file, 'utf8');
    for (const s of SERVICES) assert.ok(yml.includes(`  ${s.id}:\n    build:\n      context: "`), s.id);
    assert.equal((yml.match(/127\.0\.0\.1:/g) ?? []).length, 3);
    assert.match(yml, /"127\.0\.0\.1:13000:3000"/);
    assert.match(yml, /atc-auth\/keys:\/keys:ro/);
    assert.match(yml, /"atc-queue-data:\/sources\/atc-queue"/);
    assert.equal(yml.includes('REPLACE_WITH') || /[0-9a-f]{64}/.test(yml), false, 'no secrets in the compose file');
    const env = (/** @type {string} */ id) => Object.fromEntries(readFileSync(join(out, 'compose', 'env', `${id}.env`), 'utf8').split('\n').filter((l) => l && !l.startsWith('#')).map((l) => [l.slice(0, l.indexOf('=')), l.slice(l.indexOf('=') + 1)]));
    for (const s of SERVICES) {
      const e = env(s.id);
      assert.equal(e.HOST, '0.0.0.0', s.id);
      assert.equal(Object.values(e).some((v) => /^['"]?\.\.?\//.test(v)), false, `${s.id}: no host paths`);
      assert.equal(statSync(join(out, 'compose', 'env', `${s.id}.env`)).mode & 0o777, 0o600);
    }
    assert.equal(env('atc-backup').BACKUP_SOURCES.split(',')[0], 'atc-notify=/sources/atc-notify/notify.db');
    assert.equal(env('atc-backup').BACKUP_TREES, 'atc-media-files=/sources/atc-media/files,atc-auth-keys=/sources/atc-auth-keys,atc-audit-keys=/sources/atc-audit-keys');
    assert.match(yml, /atc-auth\/keys:\/sources\/atc-auth-keys:ro/);
    assert.equal(env('atc-status').MONITOR_SEEDS.split(',')[0], 'atc-notify=http://atc-notify:3001');
    assert.equal(env('atc-export').MEDIA_URL, 'http://atc-media:3003');
    assert.equal(env('atc-media').PUBLIC_BASE_URL, 'http://localhost:13003', 'the browser reaches media on the published port');
    assert.equal(JSON.parse(readFileSync(join(out, 'compose', 'config', 'atc-gateway', 'routes.json'), 'utf8')).jwt.jwksUrl, 'http://atc-auth:3002/.well-known/jwks.json');
    assert.equal(JSON.parse(readFileSync(join(out, 'compose', 'config', 'atc-console', 'services.json'), 'utf8')).services[0].url, 'http://atc-notify:3001');
  } finally {
    rmSync(out, { recursive: true, force: true });
  }
});

